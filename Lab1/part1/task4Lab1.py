#4. В настольной игре Скрабл (Scrabble) каждая буква имеет
#определенную ценность. В случае с английским алфавитом очки
#распределяются так:
#A, E, I, O, U, L, N, S, T, R – 1 очко;
#D, G – 2 очка;
#B, C, M, P – 3 очка;
#F, H, V, W, Y – 4 очка;
#K – 5 очков;
#J, X – 6 очков;
#Q, Z – 10 очков.
#Напишите программу, которая вычисляет стоимость введенного
#пользователем слова.
def scrabble_score(word):
    letter_scores = {
        # 1 очко
        'A': 1, 'E': 1, 'I': 1, 'O': 1, 'U': 1,
        'L': 1, 'N': 1, 'S': 1, 'T': 1, 'R': 1,
        
        # 2 очка
        'D': 2, 'G': 2,
        
        # 3 очка
        'B': 3, 'C': 3, 'M': 3, 'P': 3,
        
        # 4 очка
        'F': 4, 'H': 4, 'V': 4, 'W': 4, 'Y': 4,
        
        # 5 очков
        'K': 5,
        
        # 8 очков (в стандартном Scrabble J и X дают 8 очков)
        'J': 8, 'X': 8,
        
        # 10 очков
        'Q': 10, 'Z': 10
    }
    
    # Приводим слово к верхнему регистру для унификации
    uppercase_word = word.upper()
    total = 0
    
    # Считаем очки для каждой буквы
    for char in uppercase_word:
        if char in letter_scores:
            total += letter_scores[char]
        else:
            # Если символ не буква (пробел, цифра и т.д.) - игнорируем
            print(f"Предупреждение: символ '{char}' не учитывается")
    
    return total


print("=== КАЛЬКУЛЯТОР СКРАБЛ ===")
word = input("Введите слово для подсчета очков: ")

if word.strip():  # Проверяем, что введено не пустое слово
    result = scrabble_score(word)
    print(f"Слово: {word}")
    print(f"Очков: {result}")
else:
    print("Вы не ввели слово!")
    
